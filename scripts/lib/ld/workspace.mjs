/**
 * The dictionary workspace files (src/data/dictionary/*.json, dictionary.schema.json):
 * loading, saving, and turning records read from Living Dictionaries into workspace records.
 * Guide: docs/CONTENT-GUIDE.md section 8 · plan: docs/LD-ROADMAP.md.
 */
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from '../collect-words.mjs'
import { writeJson } from '../registry.mjs'

export const DICTIONARY_DIR = path.join(ROOT, 'src/data/dictionary')
export const FILES = {
  entries: path.join(DICTIONARY_DIR, 'entries.json'),
  sentences: path.join(DICTIONARY_DIR, 'sentences.json'),
  base: path.join(DICTIONARY_DIR, 'base.json')
}

const ABOUT = {
  entries:
    'Local copy of the Benga Living Dictionary entries, edited at /admin/living-dictionary and synced with npm run ld:pull / ld:push. Never correct Benga text by rule. Guide: docs/CONTENT-GUIDE.md section 8.',
  sentences:
    'Local copy of the Benga Living Dictionary example sentences (same rules as entries.json). Guide: docs/CONTENT-GUIDE.md section 8.',
  base: 'GENERATED by npm run ld:pull: the dictionary exactly as last read. Never edit: it is how local changes are detected.'
}

/** Fields that only exist locally (never sent to Living Dictionaries as such). */
export const LOCAL_FIELDS = ['siteKeys', 'review', 'suggestions', 'sync']

const readJson = (file, fallback) =>
  fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : fallback

export function loadWorkspace() {
  return {
    entries: readJson(FILES.entries, { entries: {} }).entries,
    sentences: readJson(FILES.sentences, { sentences: {} }).sentences,
    base: readJson(FILES.base, { entries: {}, sentences: {}, pulledAt: null })
  }
}

/** Entries sorted by headword (then homograph, id) so the file reads like a dictionary. */
export function sortRecords(records, label) {
  return Object.fromEntries(
    Object.values(records)
      .sort(
        (a, b) =>
          label(a).localeCompare(label(b), 'es', { sensitivity: 'base' }) ||
          String(a.homograph ?? '').localeCompare(String(b.homograph ?? '')) ||
          a.id.localeCompare(b.id)
      )
      .map((record) => [record.id, record])
  )
}

export async function saveEntries(entries, pulledAt) {
  await writeJson(FILES.entries, {
    _about: ABOUT.entries,
    kind: 'entries',
    pulledAt,
    entries: sortRecords(entries, (entry) => entry.lexeme)
  })
}

export async function saveSentences(sentences, pulledAt) {
  await writeJson(FILES.sentences, {
    _about: ABOUT.sentences,
    kind: 'sentences',
    pulledAt,
    sentences: sortRecords(sentences, (sentence) => sentence.text)
  })
}

export async function saveBase(base) {
  await writeJson(FILES.base, {
    _about: ABOUT.base,
    kind: 'base',
    pulledAt: base.pulledAt,
    entries: sortRecords(base.entries, (entry) => entry.lexeme),
    sentences: sortRecords(base.sentences, (sentence) => sentence.text)
  })
}

/**
 * A record read from the dictionary → workspace record. Local fields of the previous workspace
 * record (links to the site, review, suggestions) are kept; the result is "synced".
 */
export function toWorkspaceRecord(ldRecord, previous = null) {
  const { updatedAt, ...fields } = ldRecord
  const previousSync = previous?.sync || {}
  return {
    ...fields,
    siteKeys: previous?.siteKeys || [],
    review: previous?.review ?? null,
    suggestions: previous?.suggestions || [],
    sync: {
      state: 'synced',
      ldUpdatedAt: updatedAt ?? null,
      version: previousSync.version ?? 0,
      lastError: null
    }
  }
}
